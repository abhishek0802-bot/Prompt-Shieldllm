"""
PromptShield LLM — reproducible robustness experiment
Dataset expected:
    prompt_injection_dataset.csv

This script:
1. Loads the official Mirza Akhi dataset.
2. Preserves the author's train/test split.
3. Creates validation only from the TRAIN split.
4. Trains:
   B1: keyword/rule baseline
   B2: word TF-IDF + Logistic Regression
   B3: character TF-IDF + Linear SVM
   P1: PromptShield hybrid (word + character TF-IDF + rules)
5. Freezes thresholds using validation data.
6. Evaluates the official held-out test split by category.
7. Saves metrics and predictions.

Important:
- Do NOT replace the official test split with a random split.
- Do NOT tune thresholds on the test set.
- No attack examples are generated by this script.
"""

from pathlib import Path
import re
import time
import json
import joblib
import numpy as np
import pandas as pd

from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.svm import LinearSVC
from sklearn.pipeline import FeatureUnion
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score, f1_score,
    confusion_matrix, average_precision_score
)

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "prompt_injection_dataset.csv"
OUT = ROOT / "results"
OUT.mkdir(exist_ok=True)

RANDOM_STATE = 42
VALIDATION_SIZE = 0.20

if not DATA.exists():
    raise FileNotFoundError(
        f"Missing {DATA.name}. Download the official CSV from the dataset repository "
        "and place it beside this script."
    )

df = pd.read_csv(DATA)

required = {"id", "prompt", "label", "category", "technique", "language", "split"}
missing = required - set(df.columns)
if missing:
    raise ValueError(f"Missing required columns: {sorted(missing)}")

df["prompt"] = df["prompt"].fillna("").astype(str)
df["label_bin"] = (
    df["label"].astype(str).str.lower().map(
        {"malicious": 1, "benign": 0, "true": 1, "false": 0, "1": 1, "0": 0}
    )
)
if df["label_bin"].isna().any():
    raise ValueError("Unexpected values found in label column.")

# Dataset integrity checks
if df["id"].duplicated().any():
    raise ValueError("Duplicate IDs detected.")

train_df = df[df["split"].astype(str).str.lower() == "train"].copy()
test_df = df[df["split"].astype(str).str.lower() == "test"].copy()

if len(train_df) == 0 or len(test_df) == 0:
    raise ValueError("Expected both train and test splits.")

# Exact prompt overlap check across official train/test
train_prompts = set(train_df["prompt"])
test_prompts = set(test_df["prompt"])
overlap = train_prompts & test_prompts

integrity = {
    "total_rows": int(len(df)),
    "train_rows": int(len(train_df)),
    "test_rows": int(len(test_df)),
    "malicious_total": int((df["label_bin"] == 1).sum()),
    "benign_total": int((df["label_bin"] == 0).sum()),
    "exact_prompt_overlap_train_test": int(len(overlap)),
}
with open(OUT / "dataset_integrity.json", "w", encoding="utf-8") as f:
    json.dump(integrity, f, indent=2)

# Validation split ONLY from training data
tr, va = train_test_split(
    train_df,
    test_size=VALIDATION_SIZE,
    stratify=train_df["label_bin"],
    random_state=RANDOM_STATE
)

X_tr, y_tr = tr["prompt"], tr["label_bin"]
X_va, y_va = va["prompt"], va["label_bin"]
X_test, y_test = test_df["prompt"], test_df["label_bin"]

# ---------------- Rule baseline ----------------
RULE_PATTERNS = [
    r"\bignore\s+(all\s+)?(previous|prior|above)\s+instructions?\b",
    r"\bdisregard\s+(all\s+)?(previous|prior|above)\s+instructions?\b",
    r"\bforget\s+(all\s+)?(previous|prior|above)\s+instructions?\b",
    r"\b(system|developer)\s+prompt\b.*\b(reveal|show|print|give)\b",
    r"\breveal\s+(the\s+)?(system|hidden)\s+(prompt|instructions?)\b",
    r"\bpretend\s+you\s+are\b.*\b(system|developer)\b",
    r"\bdo\s+not\s+follow\b.*\binstructions?\b",
]

compiled_rules = [re.compile(p, re.I) for p in RULE_PATTERNS]

def rule_score(text):
    return int(any(p.search(text) for p in compiled_rules))

def rule_predict(texts):
    return np.array([rule_score(x) for x in texts], dtype=int)

# ---------------- ML models ----------------
word_vec = TfidfVectorizer(
    lowercase=True,
    ngram_range=(1, 2),
    min_df=1,
    max_features=50000,
    sublinear_tf=True
)

char_vec = TfidfVectorizer(
    analyzer="char",
    ngram_range=(3, 5),
    min_df=1,
    max_features=50000,
    sublinear_tf=True
)

Xw_tr = word_vec.fit_transform(X_tr)
Xw_va = word_vec.transform(X_va)
Xw_test = word_vec.transform(X_test)

Xc_tr = char_vec.fit_transform(X_tr)
Xc_va = char_vec.transform(X_va)
Xc_test = char_vec.transform(X_test)

lr = LogisticRegression(
    max_iter=2000,
    class_weight="balanced",
    random_state=RANDOM_STATE
)
lr.fit(Xw_tr, y_tr)

svm = LinearSVC(
    class_weight="balanced",
    random_state=RANDOM_STATE
)
svm.fit(Xc_tr, y_tr)

# Hybrid: concatenate sparse word + character features
from scipy.sparse import hstack
Xh_tr = hstack([Xw_tr, Xc_tr])
Xh_va = hstack([Xw_va, Xc_va])
Xh_test = hstack([Xw_test, Xc_test])

hybrid = LogisticRegression(
    max_iter=2000,
    class_weight="balanced",
    random_state=RANDOM_STATE
)
hybrid.fit(Xh_tr, y_tr)

# ---------------- Threshold selection ----------------
# Select threshold on validation only by maximizing F1.
def best_threshold(scores, y):
    thresholds = np.unique(np.quantile(scores, np.linspace(0.01, 0.99, 199)))
    best_t, best_f1 = 0.0, -1
    for t in thresholds:
        pred = (scores >= t).astype(int)
        f1 = f1_score(y, pred, zero_division=0)
        if f1 > best_f1:
            best_f1, best_t = f1, float(t)
    return best_t

lr_va_score = lr.predict_proba(Xw_va)[:, 1]
hybrid_va_score = hybrid.predict_proba(Xh_va)[:, 1]
svm_va_score = svm.decision_function(Xc_va)

thresholds = {
    "tfidf_lr": best_threshold(lr_va_score, y_va),
    "char_svm": best_threshold(svm_va_score, y_va),
    "hybrid": best_threshold(hybrid_va_score, y_va),
    "rules": 0.5
}

# ---------------- Evaluation ----------------
def evaluate(name, y_true, pred, score=None):
    tn, fp, fn, tp = confusion_matrix(y_true, pred, labels=[0, 1]).ravel()
    result = {
        "detector": name,
        "accuracy": accuracy_score(y_true, pred),
        "precision": precision_score(y_true, pred, zero_division=0),
        "recall": recall_score(y_true, pred, zero_division=0),
        "f1": f1_score(y_true, pred, zero_division=0),
        "fpr": fp / (fp + tn) if (fp + tn) else 0.0,
        "fnr": fn / (fn + tp) if (fn + tp) else 0.0,
        "tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp),
    }
    if score is not None:
        result["pr_auc"] = average_precision_score(y_true, score)
    else:
        result["pr_auc"] = np.nan
    return result

test_scores = {
    "tfidf_lr": lr.predict_proba(Xw_test)[:, 1],
    "char_svm": svm.decision_function(Xc_test),
    "hybrid": hybrid.predict_proba(Xh_test)[:, 1],
}

predictions = {
    "rules": rule_predict(X_test),
    "tfidf_lr": (test_scores["tfidf_lr"] >= thresholds["tfidf_lr"]).astype(int),
    "char_svm": (test_scores["char_svm"] >= thresholds["char_svm"]).astype(int),
    "hybrid": (test_scores["hybrid"] >= thresholds["hybrid"]).astype(int),
}

rows = []
for name, pred in predictions.items():
    rows.append(
        evaluate(
            name,
            y_test,
            pred,
            None if name == "rules" else test_scores[name]
        )
    )

overall = pd.DataFrame(rows)
overall.to_csv(OUT / "overall_metrics.csv", index=False)

# Per-category analysis
category_rows = []
for category, group in test_df.groupby("category"):
    idx = group.index
    positions = test_df.index.get_indexer(idx)
    y_cat = group["label_bin"].to_numpy()

    for name, pred_all in predictions.items():
        pred = pred_all[positions]
        score = None if name == "rules" else test_scores[name][positions]
        r = evaluate(name, y_cat, pred, score)
        r["category"] = category
        r["n"] = len(group)
        category_rows.append(r)

category_metrics = pd.DataFrame(category_rows)
category_metrics.to_csv(OUT / "category_metrics.csv", index=False)

# Hard-negative analysis
hard_mask = test_df["category"].astype(str).str.lower().eq("hard_negative")
if hard_mask.any():
    hard_positions = np.flatnonzero(hard_mask.to_numpy())
    hard_true = y_test.iloc[hard_positions].to_numpy()
    hard_rows = []
    for name, pred_all in predictions.items():
        pred = pred_all[hard_positions]
        r = evaluate(name, hard_true, pred)
        r["hard_negative_n"] = len(hard_positions)
        hard_rows.append(r)
    pd.DataFrame(hard_rows).to_csv(OUT / "hard_negative_metrics.csv", index=False)

# Save model artifacts
joblib.dump(word_vec, OUT / "word_tfidf.joblib")
joblib.dump(char_vec, OUT / "char_tfidf.joblib")
joblib.dump(lr, OUT / "logistic_regression.joblib")
joblib.dump(svm, OUT / "linear_svm.joblib")
joblib.dump(hybrid, OUT / "promptshield_hybrid.joblib")

with open(OUT / "frozen_thresholds.json", "w", encoding="utf-8") as f:
    json.dump(thresholds, f, indent=2)

# Save test predictions for auditability
pred_df = test_df[["id", "prompt", "label", "category", "technique", "language"]].copy()
for name, pred in predictions.items():
    pred_df[f"{name}_prediction"] = pred
pred_df.to_csv(OUT / "test_predictions.csv", index=False)

print("\nPromptShield experiment completed.")
print(json.dumps(integrity, indent=2))
print("\nFrozen thresholds:")
print(json.dumps(thresholds, indent=2))
print("\nOverall test metrics:")
print(overall.round(4).to_string(index=False))
